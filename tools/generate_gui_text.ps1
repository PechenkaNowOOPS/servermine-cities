$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent $PSScriptRoot
$fontDir = Join-Path $root 'resource-pack/assets/gradostroy/font/book'
$textureDir = Join-Path $root 'resource-pack/assets/gradostroy/textures/font/book'
New-Item -ItemType Directory -Force -Path $fontDir,$textureDir | Out-Null
$utf8 = [Text.UTF8Encoding]::new($false)

# Use a clean, thin bitmap alphabet instead of shrinking Minecraft's default
# atlas. The vanilla Cyrillic atlas loses strokes when forced into a tiny cell,
# which is what made letters run together in the book's narrow stat panel.
$characters = -join (@(33..126) + @(1025) + @(1040..1103) + @(1105) + @(171,187,183,8212,8230) | ForEach-Object { [char]$_ })
$rows = [int][Math]::Ceiling($characters.Length / 16.0)
$cell = 12
$bitmap = [Drawing.Bitmap]::new(16 * $cell, $rows * $cell, [Drawing.Imaging.PixelFormat]::Format32bppArgb)
$graphics = [Drawing.Graphics]::FromImage($bitmap)
$graphics.Clear([Drawing.Color]::Transparent)
$graphics.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::None
$graphics.TextRenderingHint = [Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
$font = [Drawing.Font]::new('Arial', 10, [Drawing.FontStyle]::Regular, [Drawing.GraphicsUnit]::Pixel)
$brush = [Drawing.SolidBrush]::new([Drawing.Color]::White)
$widths = ''
for ($index = 0; $index -lt $characters.Length; $index++) {
    $character = $characters[$index]
    $x = ($index % 16) * $cell
    $y = [int][Math]::Floor($index / 16.0) * $cell
    $graphics.DrawString([string]$character, $font, $brush, [float]($x + 1), [float]$y)
    $lastInk = -1
    for ($gy = 0; $gy -lt $cell; $gy++) {
        for ($gx = 0; $gx -lt $cell; $gx++) {
            if ($bitmap.GetPixel($x + $gx, $y + $gy).A -gt 0) { $lastInk = [Math]::Max($lastInk, $gx) }
        }
    }
    # Fit glyphs into an eight-pixel line with a one-pixel breathing gap.
    $advance = [int][Math]::Floor(0.5 + (($lastInk + 1) * 8 / $cell)) + 1
    $widths += $advance.ToString('x')
}
$brush.Dispose(); $font.Dispose(); $graphics.Dispose()
$bitmap.Save((Join-Path $textureDir 'text.png'), [Drawing.Imaging.ImageFormat]::Png)
$bitmap.Dispose()

$charRows = @()
$padded = $characters.PadRight($rows * 16, [char]0)
for ($row = 0; $row -lt $rows; $row++) { $charRows += $padded.Substring($row * 16, 16) }
foreach ($top in @(18,27,36,45,54)) {
    $provider = @{type='bitmap';file='gradostroy:font/book/text.png';height=8;ascent=(13-$top);chars=$charRows}
    $space = @{type='space';advances=@{' '=3}}
    $fontJson = @{providers=@($space,$provider)}
    [IO.File]::WriteAllText((Join-Path $fontDir "line_$top.json"), ($fontJson | ConvertTo-Json -Depth 8), $utf8)
}
$advances = @{}
for ($amount = -256; $amount -le 256; $amount++) { $advances[[string][char](0xE100 + $amount + 256)] = $amount }
[IO.File]::WriteAllText((Join-Path $fontDir 'space.json'), (@{providers=@(@{type='space';advances=$advances})} | ConvertTo-Json -Depth 6), $utf8)
$escapedChars = $characters.Replace('\','\\').Replace('"','\"')
$java = @"
package ru.servermine.cities.gui;

/** Generated by tools/generate_gui_text.ps1 using a crisp thin pixel alphabet. */
final class BookFont {
    private static final String CHARACTERS = "$escapedChars";
    private static final String WIDTHS = "$widths";
    private BookFont() { }
    static int width(String text) {
        int width = 0;
        for (int i = 0; i < text.length(); i++) {
            int index = CHARACTERS.indexOf(text.charAt(i));
            width += text.charAt(i) == ' ' ? 3 : index < 0 ? 6 : Character.digit(WIDTHS.charAt(index), 16);
        }
        return width;
    }
    static String fit(String text, int maximum) {
        StringBuilder safe = new StringBuilder();
        text.codePoints().forEach(c -> safe.append(c == 160 || c == 8239 ? ' ' : c == ' ' || (c <= Character.MAX_VALUE && CHARACTERS.indexOf((char)c) >= 0) ? (char)c : '?'));
        if (width(safe.toString()) <= maximum) return safe.toString();
        while (!safe.isEmpty() && width(safe + "…") > maximum) safe.setLength(safe.length() - 1);
        return safe + "…";
    }
}
"@
[IO.File]::WriteAllText((Join-Path $root 'cities/cities-gui/src/main/java/ru/servermine/cities/gui/BookFont.java'), $java, $utf8)
"Generated $($characters.Length) clean pixel glyphs in a thin bitmap font."
